#!/usr/bin/env bash
# apply-theme.sh <name> — switch theme (Lua + app colors), reload
set -euo pipefail

HYPR="$HOME/.config/hypr"
THEMES="$HYPR/themes"
GEN="$HYPR/generated"
NAME="${1:-}"

if [[ -z "$NAME" ]]; then
  echo "usage: apply-theme.sh <name>" >&2
  echo "available:" >&2
  for f in "$THEMES"/*.palette; do
    [[ -e "$f" ]] && basename "$f" .palette >&2
  done
  exit 1
fi

PAL="$THEMES/$NAME.palette"
CONF="$THEMES/$NAME.conf"
LUA="$THEMES/$NAME.lua"

if [[ ! -f "$PAL" || ! -f "$LUA" ]]; then
  echo "error: theme '$NAME' not found (need $NAME.palette and $NAME.lua)" >&2
  exit 1
fi

# Load palette into env (safe KEY=VAL lines only)
set -a
while IFS= read -r line; do
  [[ "$line" =~ ^[A-Za-z_][A-Za-z0-9_]*= ]] || continue
  eval "$line"
done < "$PAL"
set +a

mkdir -p "$GEN"

# Session env for hyprctl when launched outside the session
if [[ -z "${HYPRLAND_INSTANCE_SIGNATURE:-}" || ! -S "/run/user/$(id -u)/hypr/${HYPRLAND_INSTANCE_SIGNATURE}/.socket.sock" ]]; then
  if [[ -d /run/user/$(id -u)/hypr ]]; then
    # newest live socket (mtime)
    export HYPRLAND_INSTANCE_SIGNATURE="$(ls -1t /run/user/$(id -u)/hypr 2>/dev/null | while read -r d; do
      [[ -S "/run/user/$(id -u)/hypr/$d/.socket.sock" ]] && { echo "$d"; break; }
    done)"
  fi
fi
if [[ -z "${WAYLAND_DISPLAY:-}" && -n "${HYPRLAND_INSTANCE_SIGNATURE:-}" ]]; then
  hypr_pid="$(hyprctl instances 2>/dev/null | sed -n 's/.*pid: \([0-9]*\).*/\1/p' | head -n1)"
  if [[ -n "${hypr_pid}" && -r "/proc/${hypr_pid}/environ" ]]; then
    export WAYLAND_DISPLAY="$(tr '\0' '\n' < "/proc/${hypr_pid}/environ" | sed -n 's/^WAYLAND_DISPLAY=//p' | head -n1)"
  fi
fi

# --- symlinks (hyprland.lua requires themes.current) ---
ln -sfn "$NAME.lua" "$THEMES/current.lua"
[[ -f "$CONF" ]] && ln -sfn "$NAME.conf" "$THEMES/current.conf"
printf '%s\n' "$NAME" > "$THEMES/current"

# --- kitty ---
cat > "$GEN/kitty.conf" <<EOF
# generated by apply-theme.sh — do not edit
foreground           ${FG:-e5e9f0}
background           ${BG:-0f1419}
selection_foreground ${FG:-e5e9f0}
selection_background ${BORDER_DIM:-2e3440}
cursor               ${ACCENT:-88c0d0}
cursor_text_color    ${BG:-0f1419}

color0  ${KittyColor0:-000000}
color1  ${KittyColor1:-ff0000}
color2  ${KittyColor2:-00ff00}
color3  ${KittyColor3:-ffff00}
color4  ${KittyColor4:-0000ff}
color5  ${KittyColor5:-ff00ff}
color6  ${KittyColor6:-00ffff}
color7  ${KittyColor7:-ffffff}
color8  ${KittyColor8:-555555}
color9  ${KittyColor9:-ff5555}
color10 ${KittyColor10:-55ff55}
color11 ${KittyColor11:-ffff55}
color12 ${KittyColor12:-5555ff}
color13 ${KittyColor13:-ff55ff}
color14 ${KittyColor14:-55ffff}
color15 ${KittyColor15:-ffffff}
EOF

# --- mako ---
mkdir -p "$HOME/.config/mako"
cat > "$HOME/.config/mako/config" <<EOF
# generated by apply-theme.sh — do not edit
background-color=#${BG}ee
text-color=#${FG}
border-color=#${ACCENT}
progress-color=over #${ACCENT}
border-size=2
border-radius=0
padding=10,14
margin=8
width=320
height=110
default-timeout=5000
ignore-timeout=0
font=JetBrains Mono Nerd Font 10
icons=1
max-visible=5
layer=overlay
anchor=top-right
EOF

# --- hyprlauncher ---
mkdir -p "$HOME/.config/hypr"
cat > "$HYPR/hyprlauncher.conf" <<EOF
# generated by apply-theme.sh — do not edit
background = ${BG}ee
text-color = ${FG}ff
prompt-color = ${ACCENT}ff
placeholder-color = ${ON_SURFACE_VARIANT}ff
input-color = ${FG}ff
match-color = ${ACCENT}ff
selection-color = ${BORDER_DIM}ff
border-color = ${ACCENT}ff
border-size = 1
border-radius = 0
font = JetBrains Mono Nerd Font
width = 480
lines = 10
EOF

# --- waybar CSS vars ---
hex8_to_rgba() {
  local h="${1#\#}"
  if [[ ${#h} -eq 8 ]]; then
    local r g b a
    r=$((16#${h:0:2})); g=$((16#${h:2:2})); b=$((16#${h:4:2})); a=$((16#${h:6:2}))
    printf 'rgba(%d, %d, %d, %.2f)' "$r" "$g" "$b" "$(awk -v a="$a" 'BEGIN{printf "%.2f", a/255}')"
  else
    printf '#%s' "$h"
  fi
}

cat > "$GEN/waybar.css" <<EOF
/* generated by apply-theme.sh — do not edit */
@define-color accent #${ACCENT};
@define-color accent-dim $(hex8_to_rgba "${ACCENT_DIM:-${ACCENT}}");
@define-color bg #${BG};
@define-color fg #${FG};
@define-color surface #${SURFACE};
@define-color surface-hi #${SURFACE_HI};
@define-color border-dim #${BORDER_DIM};
@define-color on-surface #${ON_SURFACE};
@define-color on-surface-variant #${ON_SURFACE_VARIANT};
@define-color error #${ERROR};
@define-color success #${SUCCESS};
@define-color warning #${WARNING};
EOF

# --- hyprlock ---
cat > "$HYPR/hyprlock.conf" <<EOF
# generated by apply-theme.sh — do not edit
\$font = JetBrains Mono Nerd Font

general {
    hide_cursor = false
    no_fade_in = false
    ignore_empty_input = false
}

background {
    monitor =
    path = ${WALLPAPER}
    blur_passes = 3
    blur_size = 6
    noise = 0.01
    contrast = 0.9
    brightness = 0.55
    vibrancy = 0.2
    vibrancy_darkness = 0.5
}

label {
    monitor =
    text = \$TIME
    font_size = 96
    font_family = \$font
    color = rgba(${FG}ff)
    position = 0, 90
    halign = center
    valign = center
}

label {
    monitor =
    text = cmd[update:1000] date +"%A, %B %d"
    font_size = 18
    font_family = \$font
    color = rgba(${ON_SURFACE_VARIANT}ff)
    position = 0, 30
    halign = center
    valign = center
}

input-field {
    monitor =
    size = 240, 48
    outline_thickness = 2
    dots_size = 0.25
    dots_spacing = 0.35
    dots_center = true
    outer_color = rgba(${ACCENT}cc)
    inner_color = rgba(${BG}ee)
    font_color = rgba(${FG}ff)
    fade_on_empty = false
    placeholder_text = <span foreground="##${ON_SURFACE_VARIANT}">password…</span>
    fail_text = <span foreground="##${ERROR}">\( \$FPRINTFAIL \)</span>
    check_color = rgba(${SUCCESS}ff)
    fail_color = rgba(${ERROR}ff)
    position = 0, -40
    halign = center
    valign = center
    rounding = 0
}

label {
    monitor =
    text = locking…
    font_size = 14
    font_family = \$font
    color = rgba(${ON_SURFACE_VARIANT}aa)
    position = 0, -110
    halign = center
    valign = center
}
EOF

# --- GTK accent css ---
cat > "$GEN/gtk.css" <<EOF
/* generated by apply-theme.sh — do not edit */
@define-color accent_bg_color #${ACCENT};
@define-color accent_fg_color #${BG};
@define-color accent_color #${ACCENT};
@define-color window_bg_color #${BG};
@define-color window_fg_color #${FG};
@define-color view_bg_color #${SURFACE};
@define-color view_fg_color #${FG};
@define-color headerbar_bg_color #${SURFACE};
@define-color headerbar_fg_color #${FG};
@define-color sidebar_bg_color #${SURFACE};
@define-color card_bg_color #${SURFACE_HI};
@define-color card_fg_color #${FG};
@define-color dialog_bg_color #${SURFACE};
@define-color popover_bg_color #${SURFACE_HI};
@define-color border-color #${BORDER_DIM};

selection {
    background-color: alpha(#${ACCENT}, 0.35);
    color: #${FG};
}

:focus {
    outline-color: #${ACCENT};
}
EOF

mkdir -p "$HOME/.config/gtk-3.0" "$HOME/.config/gtk-4.0"
cp "$GEN/gtk.css" "$HOME/.config/gtk-3.0/gtk.css"
cp "$GEN/gtk.css" "$HOME/.config/gtk-4.0/gtk.css"

cp "$HOME/.config/mako/config" "$GEN/mako" 2>/dev/null || true
cp "$HYPR/hyprlock.conf" "$GEN/hyprlock.conf" 2>/dev/null || true
cp "$HYPR/hyprlauncher.conf" "$GEN/hyprlauncher.conf" 2>/dev/null || true

# --- hyprpaper ---
if [[ -n "${WALLPAPER:-}" && -f "${WALLPAPER}" ]]; then
  cat > "$HYPR/hyprpaper.conf" <<PEOF
# hyprpaper (rewritten by apply-theme.sh)
wallpaper {
    monitor =
    path = ${WALLPAPER}
    fit_mode = cover
}

splash = false
ipc = on
PEOF

  if pgrep -x hyprpaper >/dev/null 2>&1; then
    if ! hyprctl hyprpaper wallpaper ",${WALLPAPER}" >/dev/null 2>&1; then
      systemctl --user try-restart hyprpaper.service >/dev/null 2>&1 || true
      for _ in $(seq 1 20); do
        hyprctl hyprpaper listactive >/dev/null 2>&1 && break
        sleep 0.1
      done
    fi
  else
    systemctl --user try-start hyprpaper.service >/dev/null 2>&1 || true
  fi
fi

# --- reload hyprland (Lua picks up current.lua) ---
hyprctl reload 2>/dev/null || true
makoctl reload 2>/dev/null || true

if pgrep -x waybar >/dev/null 2>&1; then
  systemctl --user try-restart waybar.service 2>/dev/null || {
    pkill -x waybar 2>/dev/null || true
    sleep 0.2
    systemctl --user start waybar.service 2>/dev/null || waybar >/dev/null 2>&1 &
  }
fi

echo "theme applied: $NAME"
